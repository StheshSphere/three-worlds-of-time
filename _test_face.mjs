import * as THREE from 'three';
import { readFileSync } from 'node:fs';
import { createAriFaceMakeover } from './src/core/faceMakeover.js';
import { createAriMouth } from './src/core/mouthRig.js';
const h = JSON.parse(readFileSync('/mnt/data/_mouth_fix/head.json','utf8'));
const geo = new THREE.BufferGeometry();
geo.setAttribute('position',new THREE.Float32BufferAttribute(h.positions.flat(),3));
geo.setAttribute('uv',new THREE.Float32BufferAttribute(h.uv.flat(),2));
geo.setIndex(h.indices.flat());
const bone = new THREE.Bone();bone.name='head';
const mesh = new THREE.SkinnedMesh(geo,new THREE.MeshStandardMaterial());mesh.name='Mage_Head';
const skeleton=new THREE.Skeleton([bone],[new THREE.Matrix4()]);mesh.bind(skeleton);
const oldCount=mesh.geometry.index.count;
const disposables=[];
const face=createAriFaceMakeover(mesh,bone,disposables);
if(!face)throw Error('Makeover failed to detect original model islands');
const mouth=createAriMouth(mesh,bone,disposables);
if(!mouth)throw Error('Mouth rig failed after makeover');
const all=[];bone.traverse(x=>all.push(x.name));
const pupils=all.filter(x=>x==='RoundPupil').length;
const iris=all.filter(x=>x==='IrisBrown').length;
const noses=all.filter(x=>x==='SoftButtonNose').length;
if(pupils!==2||iris!==2||noses!==1)throw Error(`Incorrect face parts: ${pupils},${iris},${noses}`);
for(const open of [0,0.2,0.75,1])mouth.setMouth({aa:open,wide:open*.6,round:1-open},open);
face.update(0.1);face.update(0.2);
const nose=bone.getObjectByName('SoftButtonNose');
if(Math.abs(nose.position.z-.895)>0.001)throw Error('Nose moved during speech');
console.log(JSON.stringify({status:'PASS',removedTriangles:face.removedTriangles,trianglesBefore:oldCount/3,trianglesAfter:mesh.geometry.index.count/3,pupils,iris,noses,faceParts:all.length,voiceMouth:!!mouth.setMouth},null,2));
